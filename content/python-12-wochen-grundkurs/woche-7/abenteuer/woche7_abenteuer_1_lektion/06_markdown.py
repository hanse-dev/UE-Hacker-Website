"""## 🎲 Kapitel 2: Das random-Modul – Orakel der Wahrscheinlichkeit

**Die wichtigsten Orakel-Zauber:**

**Zahlen erzeugen:**
- `random.randint(a, b)` - Zufällige Ganzzahl von a bis b
- `random.uniform(a, b)` - Zufällige Kommazahl von a bis b
- `random.random()` - Zufallszahl zwischen 0 und 1

**Aus Sammlungen wählen:**
- `random.choice(liste)` - Ein zufälliges Element
- `random.sample(liste, k)` - k zufällige, unterschiedliche Elemente
- `random.shuffle(liste)` - Liste mischen (verändert die Liste selbst!)

**Reproduzierbare Magie:**
- `random.seed(zahl)` - Macht \"zufällige\" Ergebnisse wiederholbar (praktisch zum Testen)"""

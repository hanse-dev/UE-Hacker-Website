"""## 📚 Archiv-Struktur 1: Die Stallkarte - Der digitale Pferdepass

**Was es ist:** Ein Dictionary ist eine Sammlung von Schlüssel-Wert-Paaren, die du mit geschweiften Klammern erstellst.

**Der Aufbau einer Stallkarte:**
```python
# Leere Stallkarte erstellen
leere_karte = {}

# Stallkarte mit Daten füllen
pferd = {\"name\": \"Thunder\", \"rasse\": \"Hannoveraner\", \"alter\": 8}
```

**Schritt-für-Schritt-Erklärung:**
1. **`{}`** - Geschweifte Klammern definieren eine Stallkarte
2. **`:`** - Doppelpunkt trennt Schlüssel vom Wert
3. **`,`** - Kommas trennen die Paare
4. **`[key]`** - Mit Schlüssel greifst du auf Daten zu

**Warum so nützlich:**
- 🎯 Daten mit Namen statt Index organisieren
- 🔍 Schneller Zugriff über Namen
- ⚡ Flexibel erweiterbar und änderbar
- 🎲 Verschiedene Datentypen mischbar"""

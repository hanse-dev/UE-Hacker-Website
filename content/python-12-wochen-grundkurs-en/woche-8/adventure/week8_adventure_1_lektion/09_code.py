# 🔍 Exercises with Artifacts

# Example 1: Creating artifacts
coordinates = (100, 200)
print(f"Coordinates: {coordinates}")

# Without brackets
position = 10, 20
print(f"Position: {position}")

# One element
single = (42,)
print(f"Single artifact: {single}")

# Access elements
print(f"\nX coordinate: {coordinates[0]}")
print(f"Y coordinate: {coordinates[1]}")
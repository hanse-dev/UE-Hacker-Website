# Example 1: Creating simple profiles
# Empty profile
empty_profile = {}
print(f"Empty profile: {empty_profile}")

# Hero profile
hero = {
    "name": "Aria",
    "hero_class": "Mage",
    "level": 15,
    "hit_points": 120
}
print(f"Hero profile: {hero}")

# Monster profile
monster = {
    "name": "Dragon",
    "type": "Fire",
    "strength": 50,
    "loot": True
}
print(f"Monster profile: {monster}")
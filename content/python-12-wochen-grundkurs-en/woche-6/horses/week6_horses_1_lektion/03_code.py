# Example 1: Creating simple lists
# Empty list
empty_list = []
print(f"Empty list: {empty_list}")

# List with horses
horses = ["Thunder", "Luna", "Storm", "Shadow"]
print(f"Horses list: {horses}")

# List with numbers
training_level = [1, 2, 3, 4, 5]
print(f"Training level: {training_level}")

# Mixed list
mixed = ["Saddle", 25, True, "Bridle"]
print(f"Mixed list: {mixed}")
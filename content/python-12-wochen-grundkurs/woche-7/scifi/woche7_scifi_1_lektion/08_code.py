# Beispiel 2: Mathematische Grundfunktionen
import math

print("=== Mathematische Funktionen ===")

# Wurzel und Potenzen
print(f"sqrt(16): {math.sqrt(16)}")
print(f"pow(2, 3): {math.pow(2, 3)}")
print(f"2**3: {2**3}")

# Runden
zahl = 3.7
print(f"\nZahl: {zahl}")
print(f"round({zahl}): {round(zahl)}")
print(f"math.ceil({zahl}): {math.ceil(zahl)}")
print(f"math.floor({zahl}): {math.floor(zahl)}")

# Absolutwert
print(f"\nmath.fabs(-5.5): {math.fabs(-5.5)}")
print(f"abs(-5.5): {abs(-5.5)}")
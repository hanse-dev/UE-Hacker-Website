"""## 🎯 Sammlungs-Technik 4: break und continue – Schleifen steuern

Wenn du eine Liste durchläufst, kannst du die Schleife gezielt steuern:

- **`break`** – Schleife sofort beenden (z.B. wenn du gefunden hast was du suchst)
- **`continue`** – aktuellen Durchlauf überspringen und mit dem nächsten weitermachen

```python
for item in liste:
    if item == \"Gesuchtes\":
        break       # gefunden – aufhören
    if item == \"Überspringen\":
        continue    # dieses Element ignorieren
    print(item)
```"""

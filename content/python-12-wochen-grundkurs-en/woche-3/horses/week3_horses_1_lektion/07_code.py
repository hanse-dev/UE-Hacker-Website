# Example 1: Jump height
height = 120
if height <= 100:
    print("⚔️ Easy jump cleared!")
else:
    print("💨 Challenging jump!")

# Example 2: Weather check
is_raining = False
if is_raining:
    print("🌧️ We'll ride in the indoor arena.")
else:
    print("☀️ Perfect for the pasture!")

# Example 3: Hay check
hay_stock = 45
need = 50
if hay_stock >= need:
    print(f"💰 Enough hay! Leftover: {hay_stock - need} kg")
else:
    print(f"❌ Not enough hay! Missing: {need - hay_stock} kg")

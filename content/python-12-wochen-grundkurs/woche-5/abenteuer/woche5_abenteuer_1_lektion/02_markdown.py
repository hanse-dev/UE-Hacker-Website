"""## Zauberformel 1: Definition - Der magische Vertrag

**Was es ist:** Eine Funktion ist ein wiederverwendbarer Code-Block, den du einmal definierst und immer wieder aufrufen kannst.

**Der Aufbau einer Funktion:**
```python
def funktions_name(parameter1, parameter2):
    \"\"\"Kurze Beschreibung des Zaubers\"\"\"
    # Code, der ausgeführt wird
    return ergebnis  # Optional: Magie-Ergebnis zurückgeben
```

**Schritt-für-Schritt-Erklärung:**
1. **`def`** - Das magische Wort, das die Funktions-Definition startet
2. **`funktions_name`** - Ein eindeutiger Name für deinen Zauber
3. **`(parameter)`** - Zutaten, die dein Zauber braucht (optional)
4. **`:`** - Beendet die Funktions-Definition
5. **`\"\"\"Docstring\"\"\"`** - Magie-Buch mit Beschreibung (sehr wichtig!)
6. **Eingerückter Code** - Der eigentliche Zauber-Code
7. **`return`** - Gibt das Ergebnis zurück (optional)

**Warum so nützlich:**
- 🎯 Code wiederverwenden statt kopieren
- 🔍 Logik organisieren und strukturieren
- ⚡ Fehler an einer Stelle beheben
- 🎲 Komplexe Probleme in kleine Teile zerlegen"""

"""## 🎯 Collection Technique 4: break and continue – Controlling Loops

When you loop through a list, you can control the loop precisely:

- **`break`** – ends the loop immediately (e.g. once you've found what you're looking for)
- **`continue`** – skips the current pass and moves on to the next one

```python
for item in list_:
    if item == \"Target\":
        break       # found it – stop
    if item == \"Skip\":
        continue    # ignore this element
    print(item)
```"""

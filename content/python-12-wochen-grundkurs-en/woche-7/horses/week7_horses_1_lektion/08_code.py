# Example 2: Basic mathematical tools
import math

print("=== Mathematical Tools ===")

# Roots and powers
print(f"sqrt(16): {math.sqrt(16)}")
print(f"pow(2, 3): {math.pow(2, 3)}")
print(f"2**3: {2**3}")

# Rounding
number = 3.7
print(f"\nNumber: {number}")
print(f"round({number}): {round(number)}")
print(f"math.ceil({number}): {math.ceil(number)}")
print(f"math.floor({number}): {math.floor(number)}")

# Absolute value
print(f"\nmath.fabs(-5.5): {math.fabs(-5.5)}")
print(f"abs(-5.5): {abs(-5.5)}")
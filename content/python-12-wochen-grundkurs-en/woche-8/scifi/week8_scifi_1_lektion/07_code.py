# 🔍 Exercises with tuples

# Example 1: Creating tuples
coordinates = (100, 200, 300)
print(f"Coordinates: {coordinates}")

# Without brackets
position = 10, 20, 30
print(f"Position: {position}")

# Single element
single = (42,)
print(f"Single element: {single}")

# Accessing elements
print(f"\nX-coordinate: {coordinates[0]}")
print(f"Y-coordinate: {coordinates[1]}")
print(f"Z-coordinate: {coordinates[2]}")
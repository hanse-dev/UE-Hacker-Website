"""# 📖 Glossary – ⚖️ Week 3 – Conditions (if-else): The Paths of Decision
> You can keep this notebook open all week.

| Term | Meaning | Example |
|------|---------|--------|
| `if` | If-condition – run code only when condition is true | `if x > 5:` |
| `elif` | Else-if – check another condition | `elif x == 5:` |
| `else` | Else – code when all conditions are false | `else:` |
| `==` | Is equal (comparison, not assignment!) | `x == 5` |
| `!=` | Is not equal | `x != 5` |
| `<` / `>` | Less than / Greater than | `x < 10` |
| `<=` / `>=` | Less than or equal / Greater than or equal | `x <= 10` |
| `and` | Both conditions must be true | `x > 0 and x < 10` |
| `or` | At least one condition must be true | `x < 0 or x > 10` |
| `not` | Reverses a truth value | `not True` → `False` |"""

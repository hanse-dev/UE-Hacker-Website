"""## 🗣️ Kapitel 1: Die gemeinsame Sprache – f-Strings

Bevor du Elemente kombinierst, brauchst du eine Sprache, um über sie zu sprechen. Ein **f-String** ist die **modernere und lesbarere** Art, Variablen in Text einzubauen. Das `f` vor den Anführungszeichen sagt Python: *\"Schau in die geschweiften Klammern!\"*

**f-String vs. `+`-Verkettung – was soll ich benutzen?**

| Methode | Beispiel | Empfehlung |
|---------|---------|------------|
| `+`-Verkettung | `\"Hallo \" + name` | funktioniert, braucht `str()` für Zahlen |
| f-String | `f\"Hallo {name}\"` | moderner, kürzer, Zahlen funktionieren direkt |

> ✅ Benutze f-Strings – sie sind klarer zu lesen und weniger fehleranfällig.
> Die `+`-Methode aus Woche 1 funktioniert aber weiterhin."""

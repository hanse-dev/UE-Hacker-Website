"""## 📚 Modul-Sammlung 1: Der Import-Protokoll - Das erste Modul

**Was es ist:** Ein Modul ist eine Sammlung von vordefinierten Funktionen, die du in dein Programm laden kannst.

**Der Aufbau eines Imports:**
```python
# Ganzes Modul importieren
import math

# Mit Alias importieren
import math as m

# Nur bestimmte Funktionen importieren
from math import pi, sqrt
```

**Schritt-für-Schritt-Erklärung:**
1. **`import`** - Schlüsselwort zum Laden
2. **`math`** - Name des Moduls
3. **`as`** - Optionaler Alias/Spitzname
4. **`from`** - Importiert spezifische Funktionen

**Warum so nützlich:**
- 🎯 Code nicht neu erfinden müssen
- 🔍 Professionelle, optimierte Funktionen
- ⚡ Dein Code bleibt übersichtlich
- 🎲 Zugriff auf spezialisierte Werkzeuge"""

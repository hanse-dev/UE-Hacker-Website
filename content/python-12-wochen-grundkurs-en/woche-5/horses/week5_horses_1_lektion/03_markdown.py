"""## 🏇 Training Method 1b: Calling Training – The Key to Application

*Defining* a training routine isn't enough – it also has to be *called*! Calling is its own topic with important rules.

### With and without parentheses

**With parentheses `function()`:** The training is executed! The parentheses tell Python: \"Run this function now\".

**Without parentheses `function`:** The training is NOT executed! You are only referencing the function object – nothing happens.

### Calling with parameters

When calling, you pass **arguments** in the parentheses: `function(argument1, argument2)`. The order must match!

### From argument to variable

**When calling:** You pass an **argument** (e.g. `\"Anna\"`)

**Inside the function:** This becomes a **variable** with the parameter name (e.g. `name`)

The parameter is a **placeholder**. When called, Python replaces it with the passed value – which is then available as a variable inside the function."""

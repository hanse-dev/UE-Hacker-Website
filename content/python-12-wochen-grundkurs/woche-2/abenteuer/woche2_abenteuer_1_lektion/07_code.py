# Beispiel 1: 🪨 Erde verschmelzen - mathematische Operationen
gold_a = 150
gold_b = 75
print(f"Gesamtgold: {gold_a + gold_b}")
print(f"Differenz: {gold_a - gold_b}")
print(f"Doppeltes Gold: {gold_a * 2}")
print(f"Geteilt: {gold_a / 3}")

# Beispiel 2: 🔥 Feuer verschmelzen - String-Operationen
vorname = "Luna"
nachname = "Silbermond"
titel = "die Weise"
voller_name = vorname + " " + nachname + " " + titel
print(f"Voller Name: {voller_name}")
print(f"Name mal 3: {vorname * 3}")

# Beispiel 3: Elemente umwandeln (Erde <-> Feuer)
alter_str = "25"
alter_int = int(alter_str)
print(f"Alter als Feuer-Element (Text): {alter_str} ({type(alter_str)})")
print(f"Alter als Erd-Element (Zahl): {alter_int} ({type(alter_int)})")

# Example 1: Strings – text data
ship_name = "Starlight"
ship_class = "Cruiser"
print(f"Ship: {ship_name}")
print(f"Class: {ship_class}")
print(f"Type: {type(ship_name)}")

# Example 2: Integers – whole numbers
crew_count = 250
deck_count = 15
print(f"Crew: {crew_count}, Decks: {deck_count}")
print(f"Type: {type(crew_count)}")

# Example 3: Floats – precise values
speed = 2.5
coordinate_x = 127.35
print(f"Speed: {speed} light years/h")
print(f"Position X: {coordinate_x}")
print(f"Type: {type(speed)}")

# Example 4: Booleans – system states
system_online = True
alarm_active = False
print(f"System online: {system_online}")
print(f"Alarm active: {alarm_active}")
print(f"Type: {type(system_online)}")
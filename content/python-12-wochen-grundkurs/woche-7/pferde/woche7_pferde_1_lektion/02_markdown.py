"""## 📚 Werkzeug-Sammlung 1: Der Import-Kasten - Das erste Modul

**Was es ist:** Ein Modul ist eine Sammlung von vordefinierten Werkzeugen, die du in dein Programm laden kannst.

**Der Aufbau eines Imports:**
```python
# Ganzes Modul importieren
import math

# Mit Alias importieren
import math as m

# Nur bestimmte Werkzeuge importieren
from math import pi, sqrt
```

**Schritt-für-Schritt-Erklärung:**
1. **`import`** - Schlüsselwort zum Laden
2. **`math`** - Name der Werkzeugkiste
3. **`as`** - Optionaler Spitzname
4. **`from`** - Importiert spezifische Werkzeuge

**Warum so nützlich:**
- 🎯 Werkzeuge nicht neu bauen müssen
- 🔍 Professionelle, optimierte Ausrüstung
- ⚡ Dein Stall bleibt übersichtlich
- 🎲 Zugriff auf spezialisierte Werkzeuge"""

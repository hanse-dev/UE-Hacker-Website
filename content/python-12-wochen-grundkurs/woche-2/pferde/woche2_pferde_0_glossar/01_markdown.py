"""# 📖 Glossar – 🐴 Woche 2 – Datentypen und Variablen: Die vier Hufschlag-Typen
> Dieses Notebook kannst du die ganze Woche offen lassen.

| Begriff | Bedeutung | Beispiel |
|---------|-----------|----------|
| `f-String` | Moderne Textformatierung mit Variablen direkt im Text | `f\"Hallo {name}\"` |
| `Float` | Kommazahl | `3.14` |
| `type()` | Datentyp einer Variable prüfen | `type(42)` → `<class 'int'>` |
| `len()` | Länge eines Textes oder einer Liste | `len(\"Hallo\")` → `5` |
| `int()` | Umwandlung in ganze Zahl | `int(\"42\")` → `42` |
| `float()` | Umwandlung in Kommazahl | `float(\"3\")` → `3.0` |
| `str()` | Umwandlung in Text | `str(42)` → `\"42\"` |
| `bool()` | Umwandlung in Wahrheitswert | `bool(0)` → `False` |
| `.upper()` | Text in Großbuchstaben umwandeln | `\"hallo\".upper()` → `\"HALLO\"` |
| `.lower()` | Text in Kleinbuchstaben umwandeln | `\"HALLO\".lower()` → `\"hallo\"` |
| `.strip()` | Leerzeichen am Rand entfernen | `\" hi \".strip()` → `\"hi\"` |
| `.split()` | Text an einem Zeichen aufteilen | `\"a,b\".split(\",\")` → `[\"a\",\"b\"]` |
| `.replace()` | Teiltext durch anderen ersetzen | `\"Hallo\".replace(\"H\",\"h\")` → `\"hallo\"` |"""

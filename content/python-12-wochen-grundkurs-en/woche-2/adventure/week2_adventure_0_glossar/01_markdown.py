"""# 📖 Glossary – 💎 Week 2 – Data Types and Variables: The Four Magical Elements
> You can keep this notebook open all week.

**The four elements and their data types:**

| Element | Data type | Term | Example |
|---------|-----------|------|---------|
| 🔥 Fire | Text | `str` | `\"Fireball\"` |
| 🪨 Earth | Whole number | `int` | `42` |
| 💧 Water | Decimal number | `float` | `3.14` |
| 💨 Air | Truth value | `bool` | `True` / `False` |

**Further terms:**

| Term | Meaning | Example |
|------|---------|---------|
| `f-string` | Modern text formatting with variables directly in the text | `f\"Hello {name}\"` |
| `type()` | Check the data type (element) of a variable | `type(42)` → `<class 'int'>` |
| `len()` | Length of a text or list | `len(\"Hello\")` → `5` |
| `int()` | Convert to a whole number (Earth element) | `int(\"42\")` → `42` |
| `float()` | Convert to a decimal number (Water element) | `float(\"3\")` → `3.0` |
| `str()` | Convert to text (Fire element) | `str(42)` → `\"42\"` |
| `bool()` | Convert to a truth value (Air element) | `bool(0)` → `False` |
| `.upper()` | Convert text to uppercase | `\"hello\".upper()` → `\"HELLO\"` |
| `.lower()` | Convert text to lowercase | `\"HELLO\".lower()` → `\"hello\"` |
| `.strip()` | Remove whitespace from the edges | `\" hi \".strip()` → `\"hi\"` |
| `.split()` | Split text at a character | `\"a,b\".split(\",\")` → `[\"a\",\"b\"]` |
| `.replace()` | Replace part of a text with another | `\"Hello\".replace(\"H\",\"h\")` → `\"hello\"` |"""

"""## System Log 1: The Loop – The Time Loop

**What it is:** A for loop repeats code for every element in a sequence.

**Structure of a for loop:**
```python
for variable in sequence:
    # Code that runs for every element
```

**Step-by-step explanation:**
1. **`for`** – The command that starts the time loop
2. **`variable`** – A placeholder that holds the current element on each pass
3. **`in`** – Connects the variable to the sequence
4. **`sequence`** – The collection we iterate through (e.g. list, string, range())
5. **`:`** – Ends the loop definition
6. **Indented code** – Runs on every pass

**The iterator:**
- The iterator is like an invisible time tracker that remembers where we are in the sequence
- It starts at the first element
- After each pass it automatically jumps to the next element
- The loop ends when no elements are left

**Why so useful:**
- 🎯 Automate repeating tasks
- 🔍 Process each element individually
- ⚡ Make code more efficient and shorter
- 🎲 Create patterns and sequences"""

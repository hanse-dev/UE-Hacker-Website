"""## System Protocol 1: Definition – The Command Code

**What it is:** A function is a reusable protocol block that you define once and can call again and again.

**The structure of a function:**
```python
def protocol_name(parameter1, parameter2):
    \"\"\"Description of the protocol\"\"\"
    # Protocol code
    return result  # Optional: return a result
```

**Step-by-step explanation:**
1. **`def`** – The command that starts the protocol definition
2. **`protocol_name`** – A unique name for your protocol
3. **`(parameter)`** – System variables (optional)
4. **`:`** – Ends the protocol definition line
5. **`\"\"\"Docstring\"\"\"`** – System manual (very important!)
6. **Indented code** – The actual protocol code
7. **`return`** – Sends the result back (optional)

**Why so useful:**
- 🎯 Reuse protocols instead of reprogramming them
- 🔍 Organize and structure the system
- ⚡ Fix errors in one place
- 🎲 Break complex systems into small parts"""

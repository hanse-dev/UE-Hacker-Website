"""### ⭐⭐⭐⭐☆ Boss-Quest 3: Das Turnier-Simulation

Simuliere ein einfaches Turnier zwischen zwei Reitern mit mehreren Disziplinen.

**Schritt 1 – Turnier initialisieren:**
Erstelle eine Funktion `initialisiere_turnier(teilnehmer1, teilnehmer2)`, die einen Startzustand mit beiden Teilnehmern (Name, Pferd, Punkte) zurückgibt

**Schritt 2 – Disziplin ausführen:**
Schreibe eine Funktion `fuehre_disziplin_aus(reiter, pferd)`, die zufällige Punkte basierend auf \"Leistung\" und \"Fehlern\" berechnet und nutze z.B. Zufallszahlen für Basis-Punkte und Fehleranzahl

**Schritt 3 – Punkte berechnen:**
Erstelle eine Funktion `berechne_punkte(basis_punkte, fehler_anzahl)`, die Abzüge für Fehler vornimmt und die endgültigen Punkte zurückgibt

**Schritt 4 – Turnier steuern:**
Schreibe eine Funktion `starte_turnier(teilnehmer_a, teilnehmer_b, max_disziplinen)`, die mehrere Disziplinen simuliert und die Punkte der Teilnehmer aktualisiert und gib am Ende Sieger, Verlierer und die Punktezahlen aus

**Bonus:** Ergänze verschiedene Disziplinen mit unterschiedlichen Schwierigkeitsgraden, die die Punkteberechnung beeinflussen."""

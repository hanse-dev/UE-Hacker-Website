"""## 📚 Archive Structure 1: The Stable Card – The Digital Horse Passport

**What it is:** A dictionary is a collection of key-value pairs that you create with curly braces.

**The layout of a stable card:**
```python
# Create an empty stable card
empty_card = {}

# Fill the stable card with data
horse = {\"name\": \"Thunder\", \"breed\": \"Hanoverian\", \"age\": 8}
```

**Step-by-step explanation:**
1. **`{}`** – Curly braces define a stable card
2. **`:`** – Colon separates the key from the value
3. **`,`** – Commas separate the pairs
4. **`[key]`** – Use a key to access data

**Why so useful:**
- 🎯 Organise data by name instead of index
- 🔍 Fast access by name
- ⚡ Flexible – easy to expand and change
- 🎲 Different data types can be mixed"""

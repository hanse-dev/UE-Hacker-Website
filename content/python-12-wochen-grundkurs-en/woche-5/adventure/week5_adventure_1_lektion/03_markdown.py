"""## Spell Formula 1b: The Key to Magic

*Defining* a function is not enough – it also has to be *called*! Calling is its own topic with important rules.

### With and Without Parentheses

**With parentheses `function()`:** The spell is executed! The parentheses tell Python: \"Run this function now\".

**Without parentheses `function`:** The spell is NOT executed! You are only referencing the function object – nothing happens.

### Calling with Parameters

When calling, you pass **arguments** in the parentheses: `function(argument1, argument2)`. The order must match!

### From Argument to Variable

**When calling:** You pass an **argument** (e.g. `\"Aria\"`)

**In the function:** It becomes a **variable** with the parameter name (e.g. `name`)

The parameter is a **placeholder**. When called, Python replaces it with the passed value – which is then available as a variable inside the function."""

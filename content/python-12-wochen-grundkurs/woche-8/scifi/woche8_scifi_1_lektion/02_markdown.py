"""## 📚 Daten-Struktur 1: Das Dictionary - Der digitale Schrank

**Was es ist:** Ein Dictionary ist eine Sammlung von Schlüssel-Wert-Paaren, die du mit geschweiften Klammern erstellst.

**Der Aufbau eines Dictionary:**
```python
# Leeres Dictionary erstellen
leeres_dict = {}

# Dictionary mit Elementen erstellen
schiff = {\"name\": \"Nebula-Explorer\", \"typ\": \"Forschung\", \"crew\": 150}
```

**Schritt-für-Schritt-Erklärung:**
1. **`{}`** - Geschweifte Klammern definieren ein Dictionary
2. **`:`** - Doppelpunkt trennt Schlüssel vom Wert
3. **`,`** - Kommas trennen die Paare
4. **`[key]`** - Mit Schlüssel greifst du auf Werte zu

**Warum so nützlich:**
- 🎯 Daten mit Namen statt Index organisieren
- 🔍 Schneller Zugriff über Schlüssel
- ⚡ Flexibel erweiterbar und änderbar
- 🎲 Verschiedene Datentypen mischbar"""

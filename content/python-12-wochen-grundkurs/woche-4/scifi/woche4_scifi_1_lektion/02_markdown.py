"""## Systemprotokoll 1: Schleife - Der Zeit-Loop

**Was es ist:** Eine for-Schleife wiederholt Code für jedes Element in einer Sequenz.

**Der Aufbau einer for-Schleife:**
```python
for variable in sequenz:
    # Code, der für jedes Element ausgeführt wird
```

**Schritt-für-Schritt-Erklärung:**
1. **`for`** - Das Kommando, das den Zeit-Loop startet
2. **`variable`** - Ein Platzhalter, der bei jedem Durchlauf das aktuelle Element enthält
3. **`in`** - Verbindet die Variable mit der Sequenz
4. **`sequenz`** - Die Sammlung, durch die wir durchgehen (z.B. Liste, String, range())
5. **`:`** - Beendet die Schleifen-Definition
6. **Eingerückter Code** - Wird bei jedem Durchlauf ausgeführt

**Der Iterator:**
- Der Iterator ist wie ein unsichtbarer Zeit-Messer, der sich merkt, wo wir in der Sequenz sind
- Er startet beim ersten Element
- Nach jedem Durchlauf springt er automatisch zum nächsten Element
- Die Schleife endet, wenn kein Element mehr übrig ist

**Warum so nützlich:**
- 🎯 Automatisiere wiederholende Aufgaben
- 🔍 Verarbeite jedes Element einzeln
- ⚡ Mache Code effizienter und kürzer
- 🎲 Erstelle Muster und Sequenzen"""

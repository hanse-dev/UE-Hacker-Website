# Beispiel 1: Verschiedene Variablentypen
pferd_name = "Bobby"       # Text (String)
pferd_alter = 5            # Zahl (Integer)
pferd_groesse = 150        # Zahl (Integer)

# Beispiel 2: Variablen ausgeben
print("Pferdename:")
print(pferd_name)
print("Alter:")
print(pferd_alter)
print("Größe in cm:")
print(pferd_groesse)

# Beispiel 3: Variablen können sich ändern
print("Futter vor dem Training: " + str(2) + " kg")
futter_menge = 3  # Nach Training mehr Futter
print("Futter nach dem Training: " + str(futter_menge) + " kg")
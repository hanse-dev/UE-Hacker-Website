# Beispiel 1: Verschiedene Variablentypen
schiff_name = "Enterprise"    # Text (String)
besatzung = 150              # Zahl (Integer)
geschwindigkeit = 5          # Zahl (Integer)

# Beispiel 2: Variablen ausgeben
print("Schiffsname:")
print(schiff_name)
print("Besatzung:")
print(besatzung)
print("Lichtgeschwindigkeit:")
print(geschwindigkeit)

# Beispiel 3: Variablen können sich ändern
print("Energie vor dem Sprung: " + str(80) + "%")
energie = 45  # Nach Sprung
print("Energie nach dem Sprung: " + str(energie) + "%")
"""## Spell 1: The for Loop – Circle of Things

A `for` loop runs code for **every element** in a collection. The most natural pattern is to iterate over a list:

```python
for element in list_:
    # Code for every element
```

**Step by step:**
1. Python takes the first element from the list
2. Stores it in `element`
3. Runs the indented code
4. Repeats that for every further element

`range(n)` is a special case – it creates a sequence of numbers (0, 1, 2 … n-1) when you don't have an actual list but need a specific number of repetitions."""

"""## Datenstruktur 1b

Um alle Einträge eines Dictionaries zu verarbeiten, gibt es drei Methoden:

| Methode | Liefert | Beispiel |
|---------|---------|----------|
| `.keys()` | alle Schlüssel | `for k in held.keys()` |
| `.values()` | alle Werte | `for v in held.values()` |
| `.items()` | Schlüssel + Wert als Paar | `for k, v in held.items()` |

`.items()` ist am nützlichsten – du bekommst beides auf einmal."""

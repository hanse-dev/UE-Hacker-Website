"""## 🎲 Chapter 2: The random Module – Oracle of Chance

**The most important oracle spells:**

**Generating numbers:**
- `random.randint(a, b)` - Random whole number from a to b
- `random.uniform(a, b)` - Random decimal number from a to b
- `random.random()` - Random number between 0 and 1

**Choosing from collections:**
- `random.choice(list)` - One random element
- `random.sample(list, k)` - k random, distinct elements
- `random.shuffle(list)` - Shuffle a list (changes the list itself!)

**Reproducible magic:**
- `random.seed(number)` - Makes \"random\" results repeatable (handy for testing)"""

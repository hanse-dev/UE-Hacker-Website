# Example 1: Fusing 🪨 Earth - mathematical operations
gold_a = 150
gold_b = 75
print(f"Total gold: {gold_a + gold_b}")
print(f"Difference: {gold_a - gold_b}")
print(f"Double gold: {gold_a * 2}")
print(f"Divided: {gold_a / 3}")

# Example 2: Fusing 🔥 Fire - string operations
first_name = "Luna"
last_name = "Silvermoon"
title = "the Wise"
full_name = first_name + " " + last_name + " " + title
print(f"Full name: {full_name}")
print(f"Name x3: {first_name * 3}")

# Example 3: Converting elements (Earth <-> Fire)
age_str = "25"
age_int = int(age_str)
print(f"Age as Fire element (text): {age_str} ({type(age_str)})")
print(f"Age as Earth element (number): {age_int} ({type(age_int)})")

"""## Data Structure 1b

To process all entries of a dictionary, there are three methods:

| Method | Returns | Example |
|--------|---------|-------|
| `.keys()` | all keys | `for k in hero.keys()` |
| `.values()` | all values | `for v in hero.values()` |
| `.items()` | key + value as pair | `for k, v in hero.items()` |

`.items()` is the most useful – you get both at once."""

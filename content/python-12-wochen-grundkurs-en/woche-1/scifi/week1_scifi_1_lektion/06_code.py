# Example 1: Different variable types
ship_name = "Enterprise"     # Text (String)
crew = 150                   # Number (Integer)
speed = 5                    # Number (Integer)

# Example 2: Output variables
print("Ship name:")
print(ship_name)
print("Crew:")
print(crew)
print("Light speed factor:")
print(speed)

# Example 3: Variables can change
print("Energy before jump: " + str(80) + "%")
energy = 45  # After jump
print("Energy after jump: " + str(energy) + "%")
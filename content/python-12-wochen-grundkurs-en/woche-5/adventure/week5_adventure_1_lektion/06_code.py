# Example 1: Simple function without parameters
def greet_adventurer():
    """Greets a brave adventurer"""
    print("Welcome, brave hero!")
    print("Your adventure begins now!")

# Call the function
print("=== First call ===")
greet_adventurer()

print("\n=== Second call ===")
greet_adventurer()

print("\n=== What happens here? ===")
print("1. def greet_adventurer(): defines the function")
print("2. greet_adventurer() calls the function")
print("3. The code inside the function runs every time")
"""# 📖 Glossar – 🐴 Woche 3 – Bedingungen (if-else): Die Weichen des Reitwegs
> Dieses Notebook kannst du die ganze Woche offen lassen.

| Begriff | Bedeutung | Beispiel |
|---------|-----------|----------|
| `if` | Wenn-Bedingung – Code nur ausführen wenn Bedingung wahr | `if x > 5:` |
| `elif` | Sonst-Wenn – weitere Bedingung prüfen | `elif x == 5:` |
| `else` | Sonst – Code wenn alle Bedingungen falsch | `else:` |
| `==` | Ist gleich (Vergleich, nicht Zuweisung!) | `x == 5` |
| `!=` | Ist ungleich | `x != 5` |
| `<` / `>` | Kleiner als / Größer als | `x < 10` |
| `<=` / `>=` | Kleiner-gleich / Größer-gleich | `x <= 10` |
| `and` | Beide Bedingungen müssen wahr sein | `x > 0 and x < 10` |
| `or` | Mindestens eine Bedingung muss wahr sein | `x < 0 or x > 10` |
| `not` | Kehrt einen Wahrheitswert um | `not True` → `False` |"""

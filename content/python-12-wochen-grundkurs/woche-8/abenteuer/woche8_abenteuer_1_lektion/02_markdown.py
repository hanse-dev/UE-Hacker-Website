"""## Datenstruktur 1: Eigenschaften mit Namen

**Was es ist:** Ein Dictionary ist wie ein **Steckbrief**: Zu jeder **Eigenschaft** (Schlüssel) gehört ein **Wert**. Du erstellst ihn mit geschweiften Klammern.

**Der Aufbau eines Steckbriefs:**
```python
# Leeren Steckbrief anlegen
leerer_steckbrief = {}

# Steckbrief mit Eigenschaften füllen
held = {\"name\": \"Aria\", \"klasse\": \"Magierin\", \"level\": 15}
```

**Schritt-für-Schritt-Erklärung:**
1. **`{}`** – Geschweifte Klammern definieren einen Steckbrief
2. **`:`** – Doppelpunkt trennt Eigenschaftsname (Schlüssel) vom Wert
3. **`,`** – Kommas trennen die Einträge
4. **`[key]`** – Mit dem Schlüssel greifst du auf den Wert zu

**Warum so nützlich:**
- 🎯 Eigenschaften mit Namen statt Position (wie bei Listen)
- 🔍 Schneller Zugriff über den Schlüssel
- ⚡ Flexibel erweiterbar und änderbar
- 🎲 Verschiedene Werttypen pro Eigenschaft möglich"""

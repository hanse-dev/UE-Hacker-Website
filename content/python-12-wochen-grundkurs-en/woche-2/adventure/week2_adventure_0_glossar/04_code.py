name = "Aria"
level = 5

# f-string - variable directly in the text
print(f"Hero: {name}, Level: {level}")

# type() - check the element
print(type(name))    # <class 'str'> -> Fire element
print(type(level))   # <class 'int'> -> Earth element

# len() - length
print(len(name))     # 4

# String methods
print(name.upper())  # ARIA
print(name.lower())  # aria

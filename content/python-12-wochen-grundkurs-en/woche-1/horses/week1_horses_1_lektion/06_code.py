# Example 1: Different variable types
horse_name = "Bobby"       # Text (String)
horse_age = 5              # Number (Integer)
horse_height = 150         # Number (Integer)

# Example 2: Output variables
print("Horse name:")
print(horse_name)
print("Age:")
print(horse_age)
print("Height in cm:")
print(horse_height)

# Example 3: Variables can change
print("Feed before training: " + str(2) + " kg")
feed_amount = 3  # More feed after training
print("Feed after training: " + str(feed_amount) + " kg")
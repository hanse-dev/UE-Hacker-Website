# Beispiel 1: Einfache Listen erstellen
# Leere Liste
leere_liste = []
print(f"Leere Liste: {leere_liste}")

# Liste mit Schiffen
schiffe = ["Nebula-Explorer", "Star-Fighter", "Cargo-Hauler", "Science-Vessel"]
print(f"Schiff-Liste: {schiffe}")


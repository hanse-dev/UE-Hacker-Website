"""## 📚 Data Structure 1: The Dictionary – The Digital Cabinet

**What it is:** A dictionary is a collection of key-value pairs that you create with curly braces.

**The structure of a dictionary:**
```python
# Create an empty dictionary
empty_dict = {}

# Create a dictionary with elements
ship = {\"name\": \"Nebula-Explorer\", \"type\": \"Research\", \"crew\": 150}
```

**Step-by-step explanation:**
1. **`{}`** – Curly braces define a dictionary
2. **`:`** – Colon separates key from value
3. **`,`** – Commas separate the pairs
4. **`[key]`** – Use the key to access values

**Why so useful:**
- 🎯 Organise data with names instead of indices
- 🔍 Fast access via keys
- ⚡ Flexible – easy to extend and change
- 🎲 Mix different data types"""

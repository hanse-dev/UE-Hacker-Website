"""# 📖 Glossar – 💎 Woche 2 – Datentypen und Variablen: Die vier magischen Elemente
> Dieses Notebook kannst du die ganze Woche offen lassen.

**Die vier Elemente und ihre Datentypen:**

| Element | Datentyp | Fachbegriff | Beispiel |
|---------|----------|------------|----------|
| 🔥 Feuer | Text | `str` | `\"Feuerball\"` |
| 🪨 Erde | Ganze Zahl | `int` | `42` |
| 💧 Wasser | Kommazahl | `float` | `3.14` |
| 💨 Luft | Wahrheitswert | `bool` | `True` / `False` |

**Weitere Begriffe:**

| Begriff | Bedeutung | Beispiel |
|---------|-----------|----------|
| `f-String` | Moderne Textformatierung mit Variablen direkt im Text | `f\"Hallo {name}\"` |
| `type()` | Datentyp (Element) einer Variable prüfen | `type(42)` → `<class 'int'>` |
| `len()` | Länge eines Textes oder einer Liste | `len(\"Hallo\")` → `5` |
| `int()` | Umwandlung in ganze Zahl (Erd-Element) | `int(\"42\")` → `42` |
| `float()` | Umwandlung in Kommazahl (Wasser-Element) | `float(\"3\")` → `3.0` |
| `str()` | Umwandlung in Text (Feuer-Element) | `str(42)` → `\"42\"` |
| `bool()` | Umwandlung in Wahrheitswert (Luft-Element) | `bool(0)` → `False` |
| `.upper()` | Text in Großbuchstaben umwandeln | `\"hallo\".upper()` → `\"HALLO\"` |
| `.lower()` | Text in Kleinbuchstaben umwandeln | `\"HALLO\".lower()` → `\"hallo\"` |
| `.strip()` | Leerzeichen am Rand entfernen | `\" hi \".strip()` → `\"hi\"` |
| `.split()` | Text an einem Zeichen aufteilen | `\"a,b\".split(\",\")` → `[\"a\",\"b\"]` |
| `.replace()` | Teiltext durch anderen ersetzen | `\"Hallo\".replace(\"H\",\"h\")` → `\"hallo\"` |"""

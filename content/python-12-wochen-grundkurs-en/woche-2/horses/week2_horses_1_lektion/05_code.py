# Example 1: 🚶 Walk - Strings (text information)
horse_name = "Windstorm"
breed = "Hanoverian"
print(f"Horse: {horse_name}")
print(f"Breed: {breed}")
print(f"Type: {type(horse_name)}")

# Example 2: 🐎 Trot - Integers (whole numbers)
age = 7
height_cm = 168
print(f"Age: {age} years, Height: {height_cm} cm")
print(f"Type: {type(age)}")

# Example 3: 🏇 Canter - Floats (decimal numbers)
weight = 550.5
feed_amount = 4.25
print(f"Weight: {weight} kg, Feed: {feed_amount} kg")
print(f"Type: {type(weight)}")

# Example 4: 🦘 Jump - Booleans (truth values)
has_saddle = True
is_visited = False
print(f"Has saddle: {has_saddle}")
print(f"Is visited: {is_visited}")
print(f"Type: {type(has_saddle)}")
# Example 1: Creating simple dictionaries
# Empty dictionary
empty_dict = {}
print(f"Empty dictionary: {empty_dict}")

# Ship dictionary
ship = {
    "name": "Nebula-Explorer",
    "type": "Research",
    "crew": 150,
    "speed": 0.8
}
print(f"Ship dictionary: {ship}")

# Planet dictionary
planet = {
    "name": "Kepler-452b",
    "distance": 1400,
    "type": "Rocky planet",
    "habitable": True
}
print(f"Planet dictionary: {planet}")
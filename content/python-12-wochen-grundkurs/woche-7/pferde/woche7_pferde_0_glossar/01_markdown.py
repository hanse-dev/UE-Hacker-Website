"""# 📖 Glossar – 🐴 Woche 7 – Module und Bibliotheken: Die Werkzeugkisten des Reiterhofs!
> Dieses Notebook kannst du die ganze Woche offen lassen.

| Begriff | Bedeutung | Beispiel |
|---------|-----------|----------|
| `import` | Ein Modul (Werkzeugkasten) laden | `import math` |
| `from … import …` | Nur bestimmte Teile eines Moduls laden | `from math import sqrt` |
| `import … as …` | Modul mit Kurzname importieren | `import random as r` |
| `math.sqrt()` | Quadratwurzel berechnen | `math.sqrt(16)` → `4.0` |
| `math.floor()` | Auf ganze Zahl abrunden | `math.floor(3.9)` → `3` |
| `math.ceil()` | Auf ganze Zahl aufrunden | `math.ceil(3.1)` → `4` |
| `math.pi` | Die Kreiszahl Pi | `math.pi` → `3.14159…` |
| `random.randint()` | Zufällige ganze Zahl in einem Bereich | `random.randint(1, 6)` |
| `random.choice()` | Zufälliges Element aus einer Liste | `random.choice(liste)` |
| `random.shuffle()` | Liste zufällig durchmischen (verändert die Liste) | `random.shuffle(liste)` |"""

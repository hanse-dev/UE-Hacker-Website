# Example 1: Simple function without parameters
def greet_ranch():
    """Greets visitors at the riding ranch"""
    print("Welcome to Sunny Valley Riding Ranch!")
    print("Your training starts now!")

# Call the function
print("=== First visitor ===")
greet_ranch()

print("\n=== Second visitor ===")
greet_ranch()

print("\n=== What happens here? ===")
print("1. def greet_ranch(): defines the function")
print("2. greet_ranch() calls the function")
print("3. The code inside the function is executed every time")
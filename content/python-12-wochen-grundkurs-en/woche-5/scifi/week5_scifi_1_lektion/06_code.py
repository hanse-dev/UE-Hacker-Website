# Example 1: Simple function without parameters
def system_greeting():
    """Greets visitors on the space station"""
    print("Welcome aboard Nebula-7!")
    print("Your mission begins now!")

# Call the function
print("=== First Visitor ===")
system_greeting()

print("\n=== Second Visitor ===")
system_greeting()

print("\n=== What happens here? ===")
print("1. def system_greeting(): defines the function")
print("2. system_greeting() calls the function")
print("3. The code inside the function runs each time")
# Example 1: Creating simple stable cards
# Empty stable card
empty_card = {}
print(f"Empty stable card: {empty_card}")

# Horse stable card
horse = {
    "name": "Thunder",
    "breed": "Hanoverian",
    "age": 8,
    "height": 1.72
}
print(f"Horse stable card: {horse}")

# Rider stable card
rider = {
    "name": "Anna",
    "level": "Advanced",
    "experience": 5,
    "own_horses": True
}
print(f"Rider stable card: {rider}")
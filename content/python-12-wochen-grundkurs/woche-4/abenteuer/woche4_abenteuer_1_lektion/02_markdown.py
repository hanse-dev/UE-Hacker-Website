"""## Zauberformel 1: Schleife – Den Zirkel der Dinge

Eine `for`-Schleife führt Code für **jedes Element** in einer Sammlung aus. Das natürlichste Muster ist das Durchlaufen einer Liste:

```python
for element in liste:
    # Code für jedes Element
```

**Schritt für Schritt:**
1. Python nimmt das erste Element aus der Liste
2. Speichert es in `element`
3. Führt den eingerückten Code aus
4. Wiederholt das für jedes weitere Element

`range(n)` ist ein Sonderfall – er erzeugt eine Folge von Zahlen (0, 1, 2 … n-1) wenn du keine echte Liste hast, aber eine bestimmte Anzahl Wiederholungen brauchst."""

"""# 📖 Woche 1 – Glossar
> Dieses Notebook kannst du die ganze Woche offen lassen – hier findest du alle Begriffe auf einen Blick.

| Begriff | Bedeutung | Beispiel |
|---------|-----------|----------|
| `print()` | Gibt Text auf dem Bildschirm aus | `print(\"Hallo\")` |
| **Variable** | Behälter mit einem Namen, der einen Wert speichert | `pferd = \"Bobby\"` |
| **String** | Text – immer in Anführungszeichen | `\"Hallo Welt\"` |
| **Integer** | Ganze Zahl ohne Komma | `42` |
| **Verkettung** | Texte mit `+` zusammenfügen | `\"Hi \" + pferd` |
| `str()` | Wandelt eine Zahl in Text um | `str(42)` → `\"42\"` |
| **Kommentar** | Erklärung im Code mit `#` – wird nicht ausgeführt | `# Das ist ein Kommentar` |
| **Syntax** | Die Rechtschreibregeln von Python | Anführungszeichen nicht vergessen |
| **Ausgabe** | Was auf dem Bildschirm erscheint | Ergebnis von `print()` |
| **Fehler / Bug** | Wenn der Code nicht funktioniert | `NameError`, `TypeError` |
| **Debugging** | Einen Fehler suchen und beheben | Bug finden → Fix schreiben |
| `input()` | Liest eine Eingabe vom Benutzer ein (ergibt immer einen String) | `name = input(\"Pferdename? \")` |"""

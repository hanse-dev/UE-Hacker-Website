horse = "Bobby"
age = 5

# f-String – variable directly in text
print(f"Horse: {horse}, Age: {age}")

# type() – check type
print(type(horse))    # <class 'str'>
print(type(age))      # <class 'int'>

# len() – length
print(len(horse))     # 5

# String methods
print(horse.upper())  # BOBBY
print(horse.lower())  # bobby
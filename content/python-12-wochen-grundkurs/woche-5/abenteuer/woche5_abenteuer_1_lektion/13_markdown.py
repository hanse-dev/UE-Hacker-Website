"""## Zauberformel 2: Die Magie-Bücher

**Was es ist:** Docstrings sind Dokumentations-Strings, die erklären, was eine Funktion tut.

**Warum extrem wichtig:**
- 📖 Andere (und du später) verstehen deine Funktion
- 🔍 IDEs zeigen dir Hilfe beim Aufruf
- 🤖 Tools können automatisch Dokumentation erstellen
- ⭐ Zeichen von professionellem Code

**Die drei Arten von Docstrings:**
1. **Einzeilig:** `\"\"\"Kurze Beschreibung\"\"\"`
2. **Mehrzeilig:** `\"\"\"Kurze Beschreibung\\n\\nDetails...\"\"\"`
3. **Vollständig:** `\"\"\"Beschreibung\\n\\nArgs:\\nReturns:\\n\"\"\"`"""

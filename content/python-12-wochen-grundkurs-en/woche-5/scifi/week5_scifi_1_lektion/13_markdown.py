"""## System Protocol 2: The System Manuals

**What it is:** Docstrings are documentation strings that explain what a function does.

**Why extremely important:**
- 📖 Others (and you later) understand your function
- 🔍 IDEs show you help when calling
- 🤖 Tools can automatically generate documentation
- ⭐ Sign of professional code

**The three types of docstrings:**
1. **Single-line:** `\"\"\"Short description\"\"\"`
2. **Multi-line:** `\"\"\"Short description\\n\\nDetails...\"\"\"`
3. **Full:** `\"\"\"Description\\n\\nArgs:\\nReturns:\\n\"\"\"`"""

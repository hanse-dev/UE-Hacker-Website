"""## 📚 Training Method 1: Function Definition – The Training Plan

**What it is:** A function is a reusable training block that you define once and can call again and again.

**The structure of a function:**
```python
def training_name(parameter1, parameter2):
    \"\"\"Description of the training\"\"\"
    # Training code
    return result  # Optional: return a result
```

**Step-by-step explanation:**
1. **`def`** – The command that starts the function definition
2. **`training_name`** – A unique name for your training
3. **`(parameter)`** – Training variables (optional)
4. **`:`** – Ends the function definition
5. **`\"\"\"Docstring\"\"\"`** – Training manual (very important!)
6. **Indented code** – The actual training code
7. **`return`** – Returns the result (optional)

**Why so useful:**
- 🎯 Reuse training routines instead of rewriting them
- 🔍 Organise and structure training
- ⚡ Fix errors in one place
- 🎲 Break complex training into small parts"""

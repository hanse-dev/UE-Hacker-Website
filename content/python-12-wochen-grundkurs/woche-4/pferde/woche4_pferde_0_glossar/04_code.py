# for-Schleife über einen Text
for buchstabe in "Drache":
    print("Buchstabe:", buchstabe)

# range() – Zahlenfolge
for i in range(3):
    print("Runde", i)

# while-Schleife
futter = 3
while futter > 0:
    print("Futter:", futter, "kg")
    futter = futter - 1

# len() – Länge eines Textes
print(len("Drache"))  # 6
"""## ✨ Tool Collection 3: The random Module – The Random Horse

**The most powerful random tools:**

**Generating numbers:**
- `random.randint(a, b)` – Random integer from a to b
- `random.uniform(a, b)` – Random float from a to b
- `random.random()` – Random number between 0 and 1

**Choosing from lists:**
- `random.choice(list)` – One random element
- `random.choices(list, k=n)` – n random elements
- `random.shuffle(list)` – Shuffle a list

**Distributions:**
- `random.gauss(mu, sigma)` – Normal distribution
- `random.expovariate(lambda)` – Exponential distribution"""

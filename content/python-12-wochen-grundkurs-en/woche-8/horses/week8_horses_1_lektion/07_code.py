# 🔍 Exercises with data capsules

# Example 1: Creating capsules
coordinates = (100, 200)
print(f"Coordinates: {coordinates}")

# Without brackets
position = 10, 20
print(f"Position: {position}")

# One element
single = (42,)
print(f"Single capsule: {single}")

# Accessing elements
print(f"\nX coordinate: {coordinates[0]}")
print(f"Y coordinate: {coordinates[1]}")
# Beispiel 1: 🚶 Schritt - Strings (Textinformationen)
pferd_name = "Windsturm"
rasse = "Hannoveraner"
print(f"Pferd: {pferd_name}")
print(f"Rasse: {rasse}")
print(f"Typ: {type(pferd_name)}")

# Beispiel 2: 🐎 Trab - Integers (Ganze Zahlen)
alter = 7
stockmass = 168  # cm
print(f"Alter: {alter} Jahre, Stockmaß: {stockmass} cm")
print(f"Typ: {type(alter)}")

# Beispiel 3: 🏇 Galopp - Floats (Kommazahlen)
gewicht = 550.5
futter_menge = 4.25
print(f"Gewicht: {gewicht} kg, Futter: {futter_menge} kg")
print(f"Typ: {type(gewicht)}")

# Beispiel 4: 🦘 Sprung - Booleans (Wahrheitswerte)
hat_sattel = True
ist_besucht = False
print(f"Hat Sattel: {hat_sattel}")
print(f"Ist besucht: {ist_besucht}")
print(f"Typ: {type(hat_sattel)}")
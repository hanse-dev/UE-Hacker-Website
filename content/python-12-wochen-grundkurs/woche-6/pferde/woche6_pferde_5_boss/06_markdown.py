"""### ⭐⭐⭐⭐☆ Boss-Quest 3: Die Turnier-Datenbank

Verwalte Turniere in einer Liste: anlegen, suchen, filtern und auswerten.

**Schritt 1 – Turnier anlegen:**
Erstelle `erstelle_turnier(name, disziplin, schwierigkeit)`, die ein Dictionary mit \"name\", \"disziplin\", \"schwierigkeit\" (und optional \"status\") zurückgibt und gib das Dictionary mit `return` zurück

**Schritt 2 – Turnier zur Liste hinzufügen:**
Erstelle eine Liste `turniere` und schreibe `fuege_turnier_hinzu(turnier, turnierliste)`, die mit `append()` hinzufügt und eine Bestätigung ausgibt

**Schritt 3 – Turniere suchen:**
Schreibe `suche_turniere(turnierliste, suchbegriff)`, die alle Turniere zurückgibt, in deren Name oder Disziplin der Suchbegriff vorkommt

**Schritt 4 – Nach Status filtern:**
Erstelle `filtere_nach_status(turnierliste, status)` und gib die gefilterte Liste zurück

**Schritt 5 – Statistik ausgeben:**
Schreibe `turnier_statistik(turnierliste)`, die Anzahl und optional Verteilung nach Disziplin ausgibt; rufe im Hauptteil alle Funktionen auf

**Bonus:** Füge zu jedem Turnier ein Feld \"ergebnis\" oder \"preis\" hinzu und gib eine Erfolgsstatistik aus."""

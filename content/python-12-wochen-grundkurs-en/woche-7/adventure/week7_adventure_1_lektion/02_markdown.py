"""## 📚 Chapter 1: The Spell Import – Borrowing Foreign Magic

**What it is:** A module is a collection of predefined spells (functions) that other mages have already written. With `import` you borrow them.

**The structure of an import:**
```python
# Import the entire module
import random

# Import with a nickname
import random as r

# Import only specific spells
from string import ascii_letters
```

**Step-by-step explanation:**
1. **`import`** - Magic word for loading
2. **`random`** - Name of the library
3. **`as`** - Optional nickname
4. **`from ... import ...`** - Imports only individual spells

**Why the Archivist cares about this:**
- 🎯 No need to reinvent spells
- 🔍 Use tested, reliable incantations
- ⚡ Your code stays organised
- 🗝️ Access to specialised magic you would otherwise lack"""

age = 15

# if / elif / else
if age >= 18:
    print("Adult")
elif age >= 13:
    print("Teenager")
else:
    print("Child")

# Comparison operators
print(age == 15)   # True
print(age != 10)   # True
print(age > 10)    # True

# Logical operators
print(age > 10 and age < 20)  # True
print(age < 10 or age > 12)   # True

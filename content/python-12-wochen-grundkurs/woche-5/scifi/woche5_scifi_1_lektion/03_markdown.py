"""## Systemprotokoll 1b: Der Schlüssel zur Ausführung

Ein Protokoll zu *definieren* reicht nicht – es muss auch *aufgerufen* werden! Das Aufrufen ist ein eigenes Thema mit wichtigen Regeln.

### Mit und ohne Klammern

**Mit Klammern `funktion()`:** Das Protokoll wird ausgeführt! Die Klammern sagen Python: „Führe diese Funktion jetzt aus“.

**Ohne Klammern `funktion`:** Das Protokoll wird NICHT ausgeführt! Du referenzierst nur das Funktionsobjekt – nichts passiert.

### Aufrufen mit Parametern

Beim Aufruf übergibst du **Argumente** in den Klammern: `funktion(argument1, argument2)`. Die Reihenfolge muss stimmen!

### Vom Argument zur Variable

**Beim Aufruf:** Du übergibst ein **Argument** (z.B. `\"Alex\"`)

**In der Funktion:** Daraus wird eine **Variable** mit dem Parameternamen (z.B. `name`)

Der Parameter ist ein **Platzhalter**. Beim Aufruf ersetzt Python ihn durch den übergebenen Wert – dieser steht dann als Variable in der Funktion zur Verfügung."""

# Example 1: Creating simple lists
# Empty list
empty_list = []
print(f"Empty list: {empty_list}")

# List with treasures
treasures = ["Gold Coins", "Silver Bars", "Gems"]
print(f"Treasure list: {treasures}")

# List with numbers
levels = [1, 5, 10, 15, 20]
print(f"Level list: {levels}")

# Mixed list
mixed = ["Sword", 25, True, "Shield"]
print(f"Mixed list: {mixed}")
# Example 1: Different variable types
hero_name = "Aria"        # Text (String)
hero_level = 1            # Number (Integer)
hero_gold = 50            # Number (Integer)

# Example 2: Output variables
print("Hero name:")
print(hero_name)
print("Level:")
print(hero_level)
print("Gold:")
print(hero_gold)

# Example 3: Variables can change
print("XP before battle: " + str(0) + " XP")
hero_xp = 150  # After first battle
print("XP after battle: " + str(hero_xp) + " XP")
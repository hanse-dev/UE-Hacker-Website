"""## 📚 Tool Collection 1: The Import Box – The First Module

**What it is:** A module is a collection of predefined tools that you can load into your program.

**The structure of an import:**
```python
# Import entire module
import math

# Import with alias
import math as m

# Import only specific tools
from math import pi, sqrt
```

**Step-by-step explanation:**
1. **`import`** – keyword for loading
2. **`math`** – name of the toolbox
3. **`as`** – optional nickname
4. **`from`** – imports specific tools

**Why so useful:**
- 🎯 No need to build tools from scratch
- 🔍 Professional, optimized equipment
- ⚡ Your stable stays organized
- 🎲 Access to specialized tools"""

"""## 📚 Kapitel 1: Der Zauber-Import – Fremde Magie leihen

**Was es ist:** Ein Modul ist eine Sammlung von vordefinierten Zaubern (Funktionen), die andere Magier bereits geschrieben haben. Mit `import` leihst du sie dir aus.

**Der Aufbau eines Imports:**
```python
# Ganzes Modul importieren
import random

# Mit Spitzname importieren
import random as r

# Nur bestimmte Zauber importieren
from string import ascii_letters
```

**Schritt-für-Schritt-Erklärung:**
1. **`import`** - Zauberwort zum Laden
2. **`random`** - Name der Bibliothek
3. **`as`** - Optionaler Spitzname
4. **`from ... import ...`** - Importiert nur einzelne Zauber

**Warum das dem Archivar wichtig ist:**
- 🎯 Zauber nicht neu erfinden müssen
- 🔍 Geprüfte, zuverlässige Sprüche verwenden
- ⚡ Dein Code bleibt übersichtlich
- 🗝️ Zugriff auf spezialisierte Magie, die dir sonst fehlen würde"""

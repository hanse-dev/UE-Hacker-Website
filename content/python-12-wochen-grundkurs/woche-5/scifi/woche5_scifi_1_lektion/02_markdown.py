"""## Systemprotokoll 1: Definition - Der Befehlscode

**Was es ist:** Eine Funktion ist ein wiederverwendbarer Protokoll-Block, den du einmal definierst und immer wieder aufrufen kannst.

**Der Aufbau einer Funktion:**
```python
def protokoll_name(parameter1, parameter2):
    \"\"\"Beschreibung des Protokolls\"\"\"
    # Protokoll-Code
    return ergebnis  # Optional: Ergebnis zurückgeben
```

**Schritt-für-Schritt-Erklärung:**
1. **`def`** - Das Kommando, das die Protokoll-Definition startet
2. **`protokoll_name`** - Ein eindeutiger Name für dein Protokoll
3. **`(parameter)`** - System-Variablen (optional)
4. **`:`** - Beendet die Protokoll-Definition
5. **`\"\"\"Docstring\"\"\"`** - Systemhandbuch (sehr wichtig!)
6. **Eingerückter Code** - Der eigentliche Protokoll-Code
7. **`return`** - Gibt das Ergebnis zurück (optional)

**Warum so nützlich:**
- 🎯 Protokolle wiederverwenden statt neu programmieren
- 🔍 System organisieren und strukturieren
- ⚡ Fehler an einer Stelle beheben
- 🎲 Komplexe Systeme in kleine Teile zerlegen"""

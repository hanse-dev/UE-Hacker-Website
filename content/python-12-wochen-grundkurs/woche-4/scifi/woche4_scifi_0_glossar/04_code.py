# for-Schleife über einen Text
for buchstabe in "Drache":
    print("Buchstabe:", buchstabe)

# range() – Zahlenfolge
for i in range(3):
    print("Runde", i)

# while-Schleife
energie = 3
while energie > 0:
    print("Energie:", energie, "%")
    energie = energie - 1

# len() – Länge eines Textes
print(len("Drache"))  # 6
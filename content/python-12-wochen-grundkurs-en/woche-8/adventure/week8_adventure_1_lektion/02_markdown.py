"""## Data Structure 1: Attributes with Names

**What it is:** A dictionary is like a **profile**: every **attribute** (key) has a **value**. You create it with curly braces.

**The structure of a profile:**
```python
# Create an empty profile
empty_profile = {}

# Fill a profile with attributes
hero = {\"name\": \"Aria\", \"hero_class\": \"Mage\", \"level\": 15}
```

**Step-by-step explanation:**
1. **`{}`** – Curly braces define a profile
2. **`:`** – Colon separates the attribute name (key) from the value
3. **`,`** – Commas separate the entries
4. **`[key]`** – Use the key to access the value

**Why it's so useful:**
- 🎯 Attributes with names instead of positions (like in lists)
- 🔍 Fast access via the key
- ⚡ Flexible to extend and modify
- 🎲 Different value types per attribute possible"""

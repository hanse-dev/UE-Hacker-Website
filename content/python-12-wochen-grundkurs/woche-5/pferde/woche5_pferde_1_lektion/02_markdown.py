"""## 📚 Trainings-Methode 1: Die Funktions-Definition - Der Trainingsplan

**Was es ist:** Eine Funktion ist ein wiederverwendbarer Trainings-Block, den du einmal definierst und immer wieder aufrufen kannst.

**Der Aufbau einer Funktion:**
```python
def trainings_name(parameter1, parameter2):
    \"\"\"Beschreibung des Trainings\"\"\"
    # Trainings-Code
    return ergebnis  # Optional: Ergebnis zurückgeben
```

**Schritt-für-Schritt-Erklärung:**
1. **`def`** - Das Kommando, das die Trainings-Definition startet
2. **`trainings_name`** - Ein eindeutiger Name für dein Training
3. **`(parameter)`** - Trainings-Variablen (optional)
4. **`:`** - Beendet die Trainings-Definition
5. **`\"\"\"Docstring\"\"\"`** - Trainingshandbuch (sehr wichtig!)
6. **Eingerückter Code** - Der eigentliche Trainings-Code
7. **`return`** - Gibt das Ergebnis zurück (optional)

**Warum so nützlich:**
- 🎯 Trainings wiederverwenden statt neu schreiben
- 🔍 Training organisieren und strukturieren
- ⚡ Fehler an einer Stelle beheben
- 🎲 Komplexe Trainings in kleine Teile zerlegen"""

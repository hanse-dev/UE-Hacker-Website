# Example 1: Mathematical operations
horses_a = 12
horses_b = 8
print(f"Total horses: {horses_a + horses_b}")
print(f"Difference: {horses_a - horses_b}")
print(f"Double stables: {horses_a * 2}")
print(f"Horses per box: {horses_a / 4}")

# Example 2: String operations
name = "Star"
suffix = "light"
full_name = name + suffix
print(f"Full name: {full_name}")
print(f"Whinny: {name * 3}")

# Example 3: Type conversion
age_text = "5"
age_number = int(age_text)
print(f"Age as text: {age_text} (type: {type(age_text)})")
print(f"Age as number: {age_number} (type: {type(age_number)})")


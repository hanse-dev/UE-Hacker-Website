"""## 📚 Module Collection 1: The Import Protocol - The First Module

**What it is:** A module is a collection of predefined functions that you can load into your program.

**The structure of an import:**
```python
# Import the whole module
import math

# Import with an alias
import math as m

# Import only specific functions
from math import pi, sqrt
```

**Step-by-step explanation:**
1. **`import`** - keyword for loading
2. **`math`** - name of the module
3. **`as`** - optional alias/nickname
4. **`from`** - imports specific functions

**Why so useful:**
- 🎯 No need to reinvent the code
- 🔍 Professional, optimized functions
- ⚡ Your code stays clean and readable
- 🎲 Access to specialized tools"""

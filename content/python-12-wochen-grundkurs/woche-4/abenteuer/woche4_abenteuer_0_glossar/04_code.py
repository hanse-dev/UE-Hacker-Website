# for-Schleife über einen Text
for buchstabe in "Drache":
    print("Buchstabe:", buchstabe)

# range() – Zahlenfolge
for i in range(3):
    print("Runde", i)

# while-Schleife
leben = 3
while leben > 0:
    print("Leben:", leben)
    leben = leben - 1

# len() – Länge eines Textes
print(len("Drache"))  # 6
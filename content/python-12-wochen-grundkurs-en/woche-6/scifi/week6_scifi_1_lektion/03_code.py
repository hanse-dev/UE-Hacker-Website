# Example 1: Creating simple lists
# Empty list
empty_list = []
print(f"Empty list: {empty_list}")

# List of ships
ships = ["Nebula-Explorer", "Star-Fighter", "Cargo-Hauler", "Science-Vessel"]
print(f"Ship list: {ships}")

# List of numbers
coordinates = [100, 200, 300, 400, 500]
print(f"Coordinates: {coordinates}")

# Mixed list
mixed = ["Phaser", 25, True, "Tricorder"]
print(f"Mixed list: {mixed}")
name = "Aria"
level = 5

# f-String – Variable direkt im Text
print(f"Held: {name}, Level: {level}")

# type() – Element prüfen
print(type(name))    # <class 'str'> -> Feuer-Element
print(type(level))   # <class 'int'> -> Erd-Element

# len() – Länge
print(len(name))     # 4

# String-Methoden
print(name.upper())  # ARIA
print(name.lower())  # aria
